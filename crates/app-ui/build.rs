//! Build script for the `app-ui` binary (shipped as `branvio.exe` on Windows).
//!
//! On Windows targets it compiles a Win32 resource script containing the Branvio application
//! icon and a `VERSIONINFO` block, and links it into the executable so Explorer, the taskbar
//! and Alt-Tab show the Branvio icon and the file's "Details" tab shows product metadata.
//! On every other target it does nothing beyond the `rerun-if-changed` bookkeeping.
//!
//! # Icon resource ID
//!
//! The icon is embedded as `ICON` resource with integer ID `1`. This is load-bearing:
//! `gpui` 0.2.2 (`src/platform/windows/platform.rs`, `load_icon`) calls
//! `LoadImageW(GetModuleHandleW(None), MAKEINTRESOURCE(1), IMAGE_ICON, ..)` and registers the
//! result as the window class `hIcon`, which drives the title-bar / taskbar / Alt-Tab icon.
//! Explorer independently uses the first (lowest-ID) icon group of the executable.
//!
//! # Toolchains
//!
//! Resource compilation is driven by the `winresource` crate:
//! - `*-pc-windows-msvc`: Windows SDK `rc.exe` (located via the registry, `%RC_PATH%`, or a
//!   Developer Prompt's `%WindowsSdkVerBinPath%`). Ships with the VS Build Tools that MSVC Rust
//!   already requires. `rc.exe` from any Windows SDK since Vista accepts PNG-compressed icon
//!   entries.
//! - `*-pc-windows-gnu` / `*-gnullvm` on a Windows host: MinGW `windres` (or `llvm-windres`)
//!   plus `ar` from `PATH` (override with `%WINDRES%` / `%AR%`). `windres` and `llvm-rc` copy
//!   each icon image verbatim into its `RT_ICON` resource using the ICO directory fields
//!   (planes = 1, bit count = 32 in `branvio.ico`), so PNG-compressed entries pass through.
//!   This path is not exercised by CI; if an old `windres` rejects the PNG entries, upgrade
//!   to a current MinGW-w64 / binutils (or use the MSVC target).
//!
//! `branvio.ico` (generated by `scripts/build_app_icons.py`) holds PNG-compressed entries for
//! 16, 24, 32, 48, 64, 128 and 256 px. PNG entries require Windows Vista or newer at runtime,
//! which is far below Branvio's supported Windows baseline.
//!
//! # Cross-compilation caveat
//!
//! `winresource` is declared under `[target.'cfg(windows)'.build-dependencies]`. Cargo
//! evaluates `cfg` on *build*-dependencies against the **host** platform (build scripts run on
//! the host), so macOS/Linux hosts never download, compile or run it. The consequence is that
//! cross-compiling a Windows binary from a non-Windows host skips the icon (a `cargo:warning`
//! is emitted). Release artifacts are built natively on `windows-latest` (MSVC), where the
//! icon is always embedded and a resource-compiler failure fails the build.

use std::env;

/// Workspace-relative path of the Windows icon, relative to this crate's manifest directory.
const ICON_RELATIVE_PATH: &str = "../../packaging/windows/branvio.ico";

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={ICON_RELATIVE_PATH}");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if target_os != "windows" {
        return;
    }

    windows_resource::embed();
}

#[cfg(windows)]
mod windows_resource {
    use std::env;
    use std::path::PathBuf;

    /// `LANG_ENGLISH` / `SUBLANG_ENGLISH_US` for the `StringFileInfo` block.
    const LANG_EN_US: u16 = 0x0409;

    /// Compiles and links the icon + `VERSIONINFO` resource into the `app-ui` binary.
    ///
    /// Panics (failing the build) when the resource compiler is missing or rejects the
    /// script, so a Windows build can never silently ship without its icon.
    pub(crate) fn embed() {
        let manifest_dir = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
        let icon_path = manifest_dir.join(super::ICON_RELATIVE_PATH);
        if !icon_path.is_file() {
            panic!(
                "Windows icon not found at {}; regenerate it with scripts/build_app_icons.py",
                icon_path.display()
            );
        }
        let icon_path = icon_path.to_string_lossy().into_owned();
        let bin_name = env::var("CARGO_PKG_NAME").unwrap_or_else(|_| "app-ui".to_owned());

        // `WindowsResource::new()` already fills FileVersion / ProductVersion (strings and the
        // numeric FILEVERSION / PRODUCTVERSION fields) from `CARGO_PKG_VERSION`.
        let mut res = winresource::WindowsResource::new();
        res.set_language(LANG_EN_US)
            // Integer ID 1 — the ID gpui's `load_icon` loads; see the module docs.
            .set_icon(&icon_path)
            .set("ProductName", "Branvio")
            .set("FileDescription", "Branvio")
            .set("CompanyName", "Branvio Contributors")
            .set("LegalCopyright", "Copyright (c) Branvio Contributors")
            .set("OriginalFilename", "branvio.exe")
            .set("InternalName", "branvio");

        // `compile_for` links the resource into the binary only (not into test/bench
        // executables, which `compile()` would also do via `rustc-link-arg`).
        if let Err(err) = res.compile_for(&bin_name) {
            panic!(
                "failed to compile the Windows resource (icon + VERSIONINFO) for {bin_name}: \
                 {err}. MSVC targets need the Windows SDK `rc.exe` (set RC_PATH to override); \
                 GNU targets need `windres` and `ar` on PATH (set WINDRES / AR to override)."
            );
        }
    }
}

#[cfg(not(windows))]
mod windows_resource {
    /// Non-Windows host cross-compiling to Windows: `winresource` is intentionally not a
    /// build-dependency here (see the module docs), so the icon cannot be embedded.
    pub(crate) fn embed() {
        println!(
            "cargo:warning=cross-compiling app-ui for Windows from a non-Windows host: \
             the application icon and VERSIONINFO resource are NOT embedded; \
             build on a Windows host for release artifacts"
        );
    }
}
